@dataclass
class TypeSpecCase:
    label: str
    cl_type: str          # Common Lisp / ACL2 type-spec for (declare (type <cl_type> v)) or (the <cl_type> ...)
    outer_guard_fn: str   # Weak outer guard template with {v}, e.g. "(integerp {v})" or "t"
    good_val: str         # ACL2 literal / quoted / ground value satisfying cl_type (unquoted Lisp literal for alist)
    bad_val: str          # Concrete witness satisfying outer_guard_fn but VIOLATING cl_type!
    good_expr: str = ""   # Optional expression form if different from good_val
    bad_expr: str = ""    # Optional expression form if different from bad_val

    def g_expr(self) -> str:
        return self.good_expr if self.good_expr else self.good_val

    def b_expr(self) -> str:
        return self.bad_expr if self.bad_expr else self.bad_val


